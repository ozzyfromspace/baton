package lane

import "testing"

func TestIsCheck(t *testing.T) {
	cases := []struct {
		command string
		want    bool
	}{
		{"go test ./...", true},
		{"go test -run 'TestA|TestB' ./internal/lane", true},
		{"go vet ./internal/state", true},
		{"go -C web test ./...", true},
		{"go build ./...", false},
		{"gofmt -l internal", false},
		{"cd web && go test ./... 2>&1 | tail -50", true},
		{"GOFLAGS=-count=1 go test ./internal/loop", true},
		{"timeout 600 go test ./...", true},
		{"env CGO_ENABLED=0 go test ./...", true},
		{"time make e2e", true},
		{"pytest -x tests/", true},
		{"python3 -m pytest -k slow", true},
		{"python -m unittest discover", true},
		{"uv run pytest", true},
		{"poetry run mypy src", true},
		{"python manage.py runserver", false},
		{"npx vitest run", true},
		{"npx playwright test --project=chromium", true},
		{"npx playwright install", false},
		{"pnpm exec playwright test", true},
		{"jest --watch=false", true},
		{"cargo test --workspace", true},
		{"cargo clippy -- -D warnings", true},
		{"cargo build --release", false},
		{"make test", true},
		{"make -C web lint", true},
		{"make -j 8 check", true},
		{"make mod-test", true},
		{"make e2e BATON_E2E=1", true},
		{"make drive", true},
		{"make perf", true},
		{"make budget", true},
		{"make typecheck", true},
		{"make build", false},
		{"make release-prep VERSION=v0.8.7", false},
		{"make", false},
		{"pnpm test", true},
		{"pnpm lint", true},
		{"pnpm typecheck", true},
		{"pnpm --filter web test:e2e", true},
		{"pnpm -r type-check", true},
		{"pnpm install", false},
		{"pnpm build", false},
		{"pnpm dev", false},
		{"npm test", true},
		{"npm t", true},
		{"npm run lint", true},
		{"npm run build", false},
		{"npm lint", false}, // npm runs no script by its bare name
		{"npm ci", false},
		{"yarn test", true},
		{"yarn workspace web typecheck", true},
		{"yarn add -D vitest", false},
		{"bun test", true},
		{"turbo run test --filter=web", true},
		{"tsc --noEmit -p tsconfig.json", true},
		{"tsc -b", false},
		{"eslint .", true},
		{"ruff check .", true},
		{"ruff format .", false},
		{"ruff format --check .", true},
		{"prettier --check .", true},
		{"prettier --write .", false},
		{"./gradlew test", true},
		{"mvn verify", true},
		{"bash -c 'cd web && pnpm test'", true},
		{`sh -c "go build ./... && go test ./..."`, true},
		{"bash scripts/qa.sh", false},
		{"git commit -m 'make test pass'", false},
		{`echo "go test ./..."`, false},
		{"grep -rn 'go test' docs", false},
		{`baton verify "go test ./..." --notes "x"`, false},
		{"ls; go test ./internal/lane", true},
		{"(cd web; npm test)", true},
		{"git status\ngo test ./...", true},
		{"go \\\n  test ./...", true},
		{"", false},
		{"'unterminated", false},
	}
	for _, c := range cases {
		if got := IsCheck(c.command); got != c.want {
			t.Errorf("IsCheck(%q) = %v, want %v", c.command, got, c.want)
		}
	}
}
